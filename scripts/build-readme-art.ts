/* A little highlighter for the scene's code: TypeScript and SQL keywords, strings and
   numbers, calls, comments. */
const KEYWORDS = new Set(
  (
    'const let return async await export function if else throw new import from of ' +
    'type Record null true false CREATE TABLE TYPE AS ENUM PRIMARY KEY DEFAULT NOT NULL ' +
    'UNIQUE REFERENCES ON DELETE CASCADE INSERT INTO SELECT FROM ALTER ADD UPDATE SET ' +
    'COLUMN INDEX uuid text timestamptz'
  ).split(' '),
)
function highlight(a: App, src: string) {
  const tokens = src.match(/--.*$|\/\/.*$|'[^']*'|"[^"]*"|\d+|[A-Za-z_$][\w$]*|\s+|./g) ?? []
  return tokens
    .map((t, i) => {
      let fill = a.ink
      if (t.startsWith('--') || t.startsWith('//')) fill = a.ink3
      else if (/^['"\d]/.test(t)) fill = a.n
      else if (KEYWORDS.has(t)) fill = a.k
      else if (/^[A-Za-z_$]/.test(t) && tokens[i + 1] === '(') fill = a.f
      return fill === a.ink ? escapeXml(t) : `<tspan fill="${fill}">${escapeXml(t)}</tspan>`
    })
    .join('')
}

